def set_pixel(data: bytearray, x: int, y: int, color: int) -> None:
    offset = y * 32 + x // 2
    if x & 1:
        data[offset] = (data[offset] & 0xF0) | color
    else:
        data[offset] = (data[offset] & 0x0F) | (color << 4)


def main() -> None:
    target = Path(sys.argv[1])
    pixels = bytearray([0xBB] * 2048)
    for icon, rows in enumerate(ICONS):
        for y, row in enumerate(rows):
            for x, char in enumerate(row):
                set_pixel(pixels, (icon % 4) * 16 + x, (icon // 4) * 16 + y,
                          TRANSPARENT if char == '.' else int(char, 16))
    target.write_bytes(struct.pack('<4s6HI', b'P16\x1a', 1, 20, 64, 64, 0, 0, 2048) + pixels)


if __name__ == '__main__':
    main()
